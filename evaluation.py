def evaluate_board(): 
    score = 0
    for row in range(8):
        for col in range(8):
            piece = pieceArray[row][col]

            if piece == 0:
                continue

            score += pieceValues[piece]

            table = get_piece_table(piece)
            if piece > 0:
                score += table[row][col]
            else:
                score -= table[7 - row][col]
    return round(score,2)

def get_piece_table(piece):
    piece_type = abs(piece)
    if piece_type == 1:
        return PAWN_TABLE

    if piece_type == 2:
        return QUEEN_TABLE

    if piece_type == 3: 
        return BISHOP_TABLE

    if piece_type == 4:
        return KNIGHT_TABLE

    if piece_type == 5:
        return ROOK_TABLE

    if piece_type == 6:
        return KING_TABLE

    return None